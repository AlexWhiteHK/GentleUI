package io.github.alexwhitehk.gentleui.core.theme;

/** Color roles shared by every theme. Painters and screens never hard-code colors outside of a palette. */
public final class Palette {
	public int background;
	public int surface;
	public int surfaceVariant;
	public int outline;
	public int text;
	public int textMuted;
	public int textDisabled;
	public int accent;
	public int onAccent;
	public int accentContainer;
	public int onAccentContainer;
	public int danger;
	public int shadow;
	public int highlight;
	public boolean light;
}
