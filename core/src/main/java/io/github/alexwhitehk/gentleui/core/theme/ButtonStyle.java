package io.github.alexwhitehk.gentleui.core.theme;

public enum ButtonStyle {
	/** Strong call to action. */
	PRIMARY,
	/** Default button. */
	TONAL,
	/** Text-like button without a container until hovered. */
	GHOST,
	/** Destructive action. */
	DANGER,
	/** Item of a navigation list; {@code active} marks the current destination. */
	NAV
}
